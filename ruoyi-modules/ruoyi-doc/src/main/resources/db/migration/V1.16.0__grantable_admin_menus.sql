-- ============================================================================
-- 让「管理」能力可以由内置超管授予其他账号
--
-- 背景：此前"管理"只有唯一的内置超管能做（审计日志、系统信息、文档授权都写死
-- 判 isSuperAdmin），没有第二个管理员就无法多人维护；但也不能简单放开——
-- 必须留一个只有内置超管能做的兜底层，防止把所有人锁在系统外。
--
-- 分层（本次落地的边界）：
--   仅内置超管（兜底，不可授予）：角色权限分配、清除审计日志、站点配置、新建顶层文档区
--   可由超管授予：审计日志查看/导出、系统信息、文档授权
--
-- 「文档授权」不新增权限串：V1.9.0 建库时就已经在「全部文档」下定义了两个按钮
--   doc:perm:grant「权限分配」、doc:perm:full「完全控制」
-- 它们此前只是躺在 sys_menu 里、没有任何代码引用（"死权限串"），
-- 本次直接把它们接到 PermissionController 的注解上（二者 OR 即可）。
-- 于是不再另造 dms:perm:config 之类的同义词，角色管理里那两行的含义也就名副其实了。
--
-- 「文档授权」同时受两个条件约束：持有上述权限串之一（能力）
-- 且在该目录/文件上有「完全控制」位（范围）。
-- 这也让代码里早已声明的语义真正落地：完全控制 = 读写 + 下载 + 授权。
--
-- 幂等：menu_id 已存在则跳过。
-- ============================================================================

