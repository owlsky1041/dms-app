-- ============================================================================
-- 存量用户邮箱补全
--
-- 背景：找回密码靠邮箱发信，而 sys_user.email 之前一直允许为空，
-- 线上 12 个在用的账号都没有邮箱，一旦忘记密码只能人工进库重置。
-- 现在邮箱被改为必填（SysUserBo 加了 @NotBlank），存量数据必须先补齐，
-- 否则这些用户在「用户管理」里点保存会被校验拦住，改不动任何字段。
--
-- 补全规则：{user_name}@dms.local
--   * user_name 本身有唯一约束，因此生成的地址天然不重复；
--   * dms.local 是保留域名（RFC 6761），不会被误投到公网真实邮箱；
--   * 这是占位地址、收不到信，管理员需要在用户管理里逐条换成真实邮箱。
--     之所以不用随机串，是因为随机串既不好认也不好核对。
--
-- 幂等：只处理 NULL 或去空格后为空的邮箱，重复执行不会覆盖已填写的地址。
-- ============================================================================

UPDATE sys_user
SET email = user_name || '@dms.local'
WHERE email IS NULL OR btrim(email) = '';

-- 极端情况兜底：万一 user_name 里带空格导致生成出非法地址，用一个可用的占位替换
UPDATE sys_user
SET email = 'user' || user_id || '@dms.local'
WHERE email IS NULL OR btrim(email) = '' OR email NOT LIKE '%_@_%';
